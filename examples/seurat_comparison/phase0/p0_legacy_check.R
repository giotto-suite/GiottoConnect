options(giotto.has_conda = FALSE, giotto.no_python_warn = TRUE)
suppressMessages({ library(GiottoClass); library(SeuratObject) })
s <- readRDS(file.path(Sys.getenv("SP", tempdir()), "fixture_seurat5.rds"))
g <- suppressWarnings(GiottoClass::seuratToGiottoV5(s, spatial_assay = "Xenium", dim_reduction = c("pca","umap"), nn_network = "Xenium_nn", verbose = FALSE))
raw <- getExpression(g, values = "raw", output = "matrix"); src <- LayerData(s, "counts")
cat("raw equal:", isTRUE(all.equal(as.matrix(raw[rownames(src), colnames(src)]), as.matrix(src), check.attributes = FALSE)), "\n")
nrm <- getExpression(g, values = "normalized", output = "matrix")
cat("normalized equal:", isTRUE(all.equal(as.matrix(nrm[rownames(src), colnames(src)]), as.matrix(LayerData(s,"data")), check.attributes = FALSE)), "\n")
sl <- getSpatialLocations(g, output = "data.table"); ct <- GetTissueCoordinates(s[["fov"]], which = "centroids")
m <- merge(sl, ct, by.x = "cell_ID", by.y = "cell")
cat("locs n:", nrow(sl), " sdimx==x:", isTRUE(all.equal(m$sdimx, m$x)), " sdimy==y:", isTRUE(all.equal(m$sdimy, m$y)), " sdimy==-y:", isTRUE(all.equal(m$sdimy, -m$y)), "\n")
p <- getPolygonInfo(g, return_giottoPolygon = TRUE)
cat("polys n:", nrow(p[]), " vertices total:", nrow(terra::geom(p[])), "\n")
pca <- getDimReduction(g, reduction_method = "pca", output = "matrix")
cat("pca equal:", isTRUE(all.equal(pca[colnames(src), ], Embeddings(s, "pca")[colnames(src), ], check.attributes = FALSE)), "\n")
nn <- getNearestNetwork(g, name = "Xenium_nn", output = "data.table")
cat("nn edges:", nrow(nn), " cols:", paste(names(nn), collapse=","), "\n")
cm <- pDataDT(g); cat("cell meta cols:", paste(names(cm), collapse=","), "\n")
fm <- fDataDT(g); cat("feat meta rows:", nrow(fm), " first seurat_clusters vals:", paste(head(fm$seurat_clusters,3), collapse=","), "\n")
