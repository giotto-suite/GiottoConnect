options(giotto.has_conda = FALSE, giotto.no_python_warn = TRUE, arrow.unsafe_metadata = TRUE)
suppressMessages({ library(SeuratObject); library(GiottoClass); library(GiottoDisk) })
C <- path.expand("~/Library/Caches/org.R-project.R/R/GiottoData/xenium_mini_lung_ffpe")
cat("LoadXenium flip.xy default:", deparse(formals(Seurat::LoadXenium)$flip.xy), "\n")
raw <- as.data.frame(arrow::read_parquet(file.path(C, "cells.parquet"), col_select = c("cell_id","x_centroid","y_centroid")))
s <- readRDS(file.path(Sys.getenv("SP", tempdir()), "seurat_xenium_mini.rds"))
ct <- GetTissueCoordinates(s[["fov"]], which = "centroids")
id <- ct$cell[1]
cat("cell", id, "\n raw parquet   x,y:", unlist(raw[raw$cell_id == id, 2:3]), "\n LoadXenium    x,y:", unlist(ct[ct$cell == id, 1:2]), "\n")
proj <- file.path(Sys.getenv("SP", tempdir()), "p0_xen_disk"); unlink(proj, recursive = TRUE)
rd <- importXeniumDisk(C, backend = proj)
g <- rd$create_gobject()
print(g)
sl <- getSpatialLocations(g, output = "data.table")
cat(" importXeniumDisk sdimx,sdimy:", unlist(sl[sl$cell_ID == id, c("sdimx","sdimy")]), "\n")
cat(" n cells giottodisk:", nrow(sl), " seurat:", nrow(ct), " raw:", nrow(raw), "\n")
